-- GoBD (#143): an append-only change log filled by triggers, so changes made
-- through the CLI are recorded as well, and a hash chain over issued invoices.

CREATE TABLE audit_log (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  changed_at INTEGER NOT NULL DEFAULT (unixepoch()),
  table_name TEXT NOT NULL,
  row_id INTEGER NOT NULL,
  -- The invoice or expense a position, payment or reminder belongs to.
  parent_id INTEGER,
  action TEXT NOT NULL CHECK (action IN ('insert', 'update', 'delete', 'restore')),
  -- JSON objects: the whole row on insert/delete, only the changed columns on update.
  old_values TEXT,
  new_values TEXT
);
CREATE INDEX audit_log_row ON audit_log (table_name, row_id);
CREATE INDEX audit_log_parent ON audit_log (parent_id) WHERE parent_id IS NOT NULL;

-- One row per issue (and per reopen) of an invoice. Each row's hash covers the
-- previous row's hash, so a changed or removed row breaks the chain.
CREATE TABLE invoice_seals (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  invoice_id INTEGER NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('issue', 'reopen')),
  sealed_at INTEGER NOT NULL,
  content_hash TEXT NOT NULL,
  -- UNIQUE: two seals appended concurrently cannot both follow the same predecessor.
  prev_hash TEXT NOT NULL UNIQUE,
  hash TEXT NOT NULL UNIQUE
);
CREATE INDEX invoice_seals_invoice ON invoice_seals (invoice_id, id);

